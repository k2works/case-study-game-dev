namespace PuyoPuyo.Elmish

open Elmish
open PuyoPuyo.Domain

/// ゲームのメッセージ
type メッセージ =
    | ゲーム開始
    | ゲームリセット
    | 左移動
    | 右移動
    | 下移動
    | 回転
    | 高速落下開始
    | 高速落下停止
    | タイマー刻み
    | 新しいぷよ生成
    | ぷよ固定
    | 連鎖処理
    | ゲームオーバー確認

module 更新 =
    /// スコアを計算
    let private スコアを計算 (現在のスコア: スコア) (連鎖数: int) (最終盤面: 盤面) : スコア =
        let 連鎖スコア = if 連鎖数 > 0 then ゲームロジック.連鎖スコア計算 連鎖数 else 0
        let 更新されたスコア = スコア.スコア加算 現在のスコア 連鎖スコア
        if 盤面.全消し判定 最終盤面 then スコア.全消しボーナス加算 更新されたスコア else 更新されたスコア

    /// ゲームオーバー時のモデルを作成
    let private ゲームオーバーモデルを作成 (モデル: モデル) (最終盤面: 盤面) (最終スコア: スコア) (連鎖数: int) : モデル =
        { モデル with
            盤面 = 最終盤面
            現在のぷよ = None
            スコア = 最終スコア
            最後の連鎖数 = 連鎖数
            状態 = ゲームオーバー }

    /// ゲーム続行時のモデルを作成
    let private ゲーム続行モデルを作成 (モデル: モデル) (最終盤面: 盤面) (最終スコア: スコア) (連鎖数: int) (次のペア: ぷよペア) : モデル =
        { モデル with
            盤面 = 最終盤面
            現在のぷよ = モデル.次のぷよ
            次のぷよ = Some 次のペア
            スコア = 最終スコア
            最後の連鎖数 = 連鎖数 }

    /// ぷよ着地後の処理
    let private ぷよ着地処理 (モデル: モデル) (ペア: ぷよペア) : モデル * Cmd<メッセージ> =
        let (位置1, 位置2) = ぷよペア.位置取得 ペア
        let 固定後の盤面 = 盤面.ぷよ2つ固定 モデル.盤面 位置1 ペア.ぷよ1の色 位置2 ペア.ぷよ2の色
        let (最終盤面, 連鎖数) = 盤面.連鎖数をカウントしながら消去と重力を繰り返し適用 固定後の盤面
        let 最終スコア = スコアを計算 モデル.スコア 連鎖数 最終盤面
        let 次のペア = ぷよペア.ランダム作成 2<列> 1<行> 0<回転>

        let ゲームオーバーか =
            match モデル.次のぷよ with
            | Some ぷよ -> ゲームロジック.ゲームオーバー判定 最終盤面 ぷよ
            | None -> false

        let 新しいモデル =
            if ゲームオーバーか then
                ゲームオーバーモデルを作成 モデル 最終盤面 最終スコア 連鎖数
            else
                ゲーム続行モデルを作成 モデル 最終盤面 最終スコア 連鎖数 次のペア

        新しいモデル, Cmd.none

    /// ぷよを下に移動させる（共通処理）
    let private ぷよを落下 (モデル: モデル) : モデル * Cmd<メッセージ> =
        match モデル.現在のぷよ with
        | Some ペア ->
            match ゲームロジック.ぷよペア移動を試行 モデル.盤面 ペア 下 with
            | Some 移動後のペア -> { モデル with 現在のぷよ = Some 移動後のペア }, Cmd.none
            | None -> ぷよ着地処理 モデル ペア
        | None -> モデル, Cmd.none

    /// ゲーム開始処理
    let private ゲーム開始処理 (モデル: モデル) : モデル * Cmd<メッセージ> =
        let 現在のぷよペア = ぷよペア.ランダム作成 2<列> 1<行> 0<回転>
        let 次のぷよペア = ぷよペア.ランダム作成 2<列> 1<行> 0<回転>
        { モデル with
            盤面 = 盤面.作成 6<列> 13<行>
            現在のぷよ = Some 現在のぷよペア
            次のぷよ = Some 次のぷよペア
            スコア = スコア.作成 ()
            ゲーム時間 = 0
            状態 = プレイ中 },
        Cmd.none

    /// ぷよペアを移動（方向指定）
    let private ぷよペアを移動 (モデル: モデル) (方向: 方向) : モデル * Cmd<メッセージ> =
        match モデル.現在のぷよ with
        | Some ぷよペア ->
            match ゲームロジック.ぷよペア移動を試行 モデル.盤面 ぷよペア 方向 with
            | Some 移動後のぷよペア -> { モデル with 現在のぷよ = Some 移動後のぷよペア }, Cmd.none
            | None -> モデル, Cmd.none
        | None -> モデル, Cmd.none

    /// ぷよペアを回転
    let private ぷよペアを回転 (モデル: モデル) : モデル * Cmd<メッセージ> =
        match モデル.現在のぷよ with
        | Some ぷよペア ->
            match ゲームロジック.ぷよペア壁キック回転 モデル.盤面 ぷよペア PuyoPuyo.Domain.ぷよペア.時計回り回転 with
            | Some 回転後のぷよペア -> { モデル with 現在のぷよ = Some 回転後のぷよペア }, Cmd.none
            | None -> モデル, Cmd.none
        | None -> モデル, Cmd.none

    /// プレイ中のメッセージ処理
    let private プレイ中のメッセージ処理 (メッセージ: メッセージ) (モデル: モデル) : (モデル * Cmd<メッセージ>) option =
        if モデル.状態 <> プレイ中 then
            None
        else
            match メッセージ with
            | 下移動 -> Some(ぷよを落下 モデル)
            | 高速落下開始 -> Some({ モデル with 高速落下中 = true }, Cmd.none)
            | 高速落下停止 -> Some({ モデル with 高速落下中 = false }, Cmd.none)
            | タイマー刻み -> Some(ぷよを落下 モデル)
            | _ -> None

    /// Update 関数
    let 更新 (メッセージ: メッセージ) (モデル: モデル) : モデル * Cmd<メッセージ> =
        match プレイ中のメッセージ処理 メッセージ モデル with
        | Some 結果 -> 結果
        | None ->
            match メッセージ with
            | ゲーム開始 -> ゲーム開始処理 モデル
            | ゲームリセット -> PuyoPuyo.Elmish.モデル.初期化 (), Cmd.none
            | 左移動 -> ぷよペアを移動 モデル 左
            | 右移動 -> ぷよペアを移動 モデル 右
            | 回転 -> ぷよペアを回転 モデル
            | _ -> モデル, Cmd.none
