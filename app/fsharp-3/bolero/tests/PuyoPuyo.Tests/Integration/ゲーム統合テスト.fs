[<Fact>]
let ``ゲームオーバー判定の統合テスト`` () =
    // Arrange - 盤面の上部までぷよを積む（次のぷよが配置できない状態）
    let 初期盤面 = 盤面.作成 6<列> 13<行>

    // 列2の上部（行0〜行2）にぷよを配置して、新しいぷよペアが配置できないようにする
    let 満杯の盤面 =
        初期盤面
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 2<列> 0<行> (埋まっている 赤))
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 2<列> 1<行> (埋まっている 赤))
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 2<列> 2<行> (埋まっている 赤))

    // 次のぷよペアは列2の上部に配置しようとする
    let 次のぷよペア = ぷよペア.作成 2<列> 0<行> 青 緑 0<回転>

    // 現在のぷよペアは別の場所に配置
    let 現在のぷよペア = ぷよペア.作成 4<列> 10<行> 青 緑 0<回転>

    let モデル =
        { モデル.初期化 () with
            盤面 = 満杯の盤面
            現在のぷよ = Some 現在のぷよペア
            次のぷよ = Some 次のぷよペア
            状態 = プレイ中
            スコア = スコア.作成 () }

    // Act - 現在のぷよを落下させて固定（その後、次のぷよが配置できずゲームオーバー）
    let mutable 現在のモデル = モデル
    let mutable 反復回数 = 0

    while 現在のモデル.状態 = プレイ中 && 反復回数 < 30 do
        let (新しいモデル, _) = 更新.更新 下移動 現在のモデル
        現在のモデル <- 新しいモデル
        反復回数 <- 反復回数 + 1

    // Assert - ゲームオーバー状態になっていることを確認
    現在のモデル.状態 |> should equal ゲームオーバー
    現在のモデル.現在のぷよ |> should equal None

