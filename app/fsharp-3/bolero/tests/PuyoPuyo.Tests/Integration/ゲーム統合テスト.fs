/// ゲーム開始からぷよ配置までの一連の流れをテスト
[<Fact>]
let ``ゲーム開始からぷよペア生成までの統合テスト`` () =
    // Arrange
    let 初期モデル = モデル.初期化 ()
    初期モデル.状態 |> should equal 未開始

    // Act - ゲーム開始
    let (ゲーム開始後のモデル, _) = 更新.更新 ゲーム開始 初期モデル

