    ゲーム開始後のモデル.次のぷよ |> should not' (equal None)
    ゲーム開始後のモデル.スコア.値 |> should equal 0
    ゲーム開始後のモデル.盤面.列数 |> should equal 6
    ゲーム開始後のモデル.盤面.行数 |> should equal 13

[<Fact>]
let ``ぷよペアの移動から固定までの統合テスト`` () =
    // Arrange
    let 初期モデル = モデル.初期化 ()
    let (ゲーム開始後のモデル, _) = 更新.更新 ゲーム開始 初期モデル

    // Act - ぷよペアを右に移動
    let (右移動後のモデル, _) = 更新.更新 右移動 ゲーム開始後のモデル

    // Assert - ぷよペアが移動していることを確認
    右移動後のモデル.現在のぷよ |> should not' (equal None)
    右移動後のモデル.現在のぷよ |> should not' (equal ゲーム開始後のモデル.現在のぷよ)

    // Act - ぷよペアを落下させる
    let mutable 現在のモデル = 右移動後のモデル
    let mutable 反復回数 = 0

    // 最大20回まで下移動を試みる（盤面の高さより多い回数）
    while 現在のモデル.現在のぷよ.IsSome && 反復回数 < 20 do
        let (新しいモデル, _) = 更新.更新 下移動 現在のモデル
        現在のモデル <- 新しいモデル
        反復回数 <- 反復回数 + 1

    // Assert - ぷよペアが固定され、新しいペアが生成されていることを確認
    現在のモデル.現在のぷよ |> should not' (equal None)
    現在のモデル.盤面 |> should not' (equal 右移動後のモデル.盤面)

[<Fact>]
let ``ぷよ消去とスコア加算の統合テスト`` () =
    // Arrange - 4つの同色ぷよが縦に並ぶ状況を作成
    let 初期盤面 = 盤面.作成 6<列> 13<行>
    let 盤面3 =
        初期盤面
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 3<列> 11<行> (埋まっている 赤))
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 3<列> 10<行> (埋まっている 赤))
        |> (fun 盤 -> PuyoPuyo.Domain.盤面.セル設定 盤 3<列> 9<行> (埋まっている 赤))

    // 現在のぷよペア（赤・赤）を作成
    let 現在のぷよペア = ぷよペア.作成 3<列> 8<行> 赤 赤 0<回転>
    let 次のぷよペア = ぷよペア.ランダム作成 2<列> 1<行> 0<回転>

    let モデル =
        { モデル.初期化 () with
            盤面 = 盤面3
            現在のぷよ = Some 現在のぷよペア
            次のぷよ = Some 次のぷよペア
            状態 = プレイ中
            スコア = スコア.作成 () }

    // Act - ぷよペアを下に移動させて固定
    let mutable 現在のモデル = モデル
    let mutable 反復回数 = 0

    while 現在のモデル.現在のぷよ = Some 現在のぷよペア && 反復回数 < 20 do
        let (新しいモデル, _) = 更新.更新 下移動 現在のモデル
        現在のモデル <- 新しいモデル
        反復回数 <- 反復回数 + 1

    // Assert - スコアが加算されていることを確認
    現在のモデル.スコア.値 |> should be (greaterThan 0)
    現在のモデル.最後の連鎖数 |> should equal 1

    // 固定後、ぷよが消去されているはず
    // 新しいぷよペアが生成されているはず
    現在のモデル.現在のぷよ |> should not' (equal None)

